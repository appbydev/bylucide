import * as lucide from 'lucide-react';
import { readFileSync, writeFileSync } from 'node:fs';

// Derive aliases from component identity, never from a hand-maintained synonym list.
const root = new URL('../', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('src/icon-manifest.json', root), 'utf8')) as { icons: string[]; aliases: Record<string, string> };
const kebab = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').replace(/([a-z])([0-9])/g, '$1-$2').replace(/([0-9])([a-z])/g, '$1-$2').replace(/-([0-9])([0-9])(?=$|-)/g, '-$1-$2').toLowerCase().replace(/-3-d$/, '-3d');
const compact = (name: string) => name.replace(/-/g, '').toLowerCase();
const canonical = new Map<unknown, string>(Object.entries(lucide.icons).map(([name, component]) => [component, name]));
const exports = Object.entries(lucide).filter(([, component]) => canonical.has(component)).sort(([a], [b]) => a.localeCompare(b));
const byCompact = new Map(exports.map(([name, component]) => [compact(name), component]));
const local = new Map<unknown, string>();
for (const name of manifest.icons) {
  const component = byCompact.get(compact(name));
  // Preserve animated Lucide icons removed upstream (notably brand icons).
  if (component) local.set(component, name);
}
const names: Record<string, string> = {};
const symbols: Record<string, string> = {};
for (const [component, symbol] of canonical) {
  const name = local.get(component) ?? kebab(symbol);
  symbols[name] = symbol;
}
const lines = ["// Generated by scripts/generate-icons.ts from the pinned lucide-react version. Do not edit.", "import { createIcon } from './icon-factory';"];
const primary = new Map<unknown, string>();
for (const [symbol, component] of exports) {
  const name = local.get(component) ?? kebab(canonical.get(component)!);
  names[symbol] = name;
  names[kebab(symbol)] = name;
  const existing = primary.get(component);
  lines.push(`export const ${symbol} = ${existing ?? `createIcon(${JSON.stringify(name)})`};`);
  primary.set(component, existing ?? symbol);
}
for (const name of manifest.icons) {
  names[name] = name;
  if (!byCompact.has(compact(name))) {
    const symbol = name.split('-').map(part => part[0]!.toUpperCase() + part.slice(1)).join('');
    for (const alias of [symbol, `${symbol}Icon`, `Lucide${symbol}`]) names[alias] = name;
    lines.push(`export const ${symbol} = createIcon(${JSON.stringify(name)});`, `export const ${symbol}Icon = ${symbol};`, `export const Lucide${symbol} = ${symbol};`);
  }
}
manifest.aliases = Object.fromEntries(Object.entries(names).filter(([alias, name]) => alias !== name && alias === alias.toLowerCase()));
writeFileSync(new URL('src/icon-manifest.json', root), JSON.stringify(manifest, null, 2) + '\n');
writeFileSync(new URL('src/lucide-catalog.ts', root), '// Generated by scripts/generate-icons.ts. Official Lucide names only.\n' + `export const lucideNames: Readonly<Record<string, string>> = ${JSON.stringify(names, null, 2)};\n` + `export const lucideSymbols: Readonly<Record<string, string>> = ${JSON.stringify(symbols, null, 2)};\n`);
writeFileSync(new URL('src/icon-exports.ts', root), lines.join('\n') + '\n');
console.log(`Generated ${exports.length} official exports (${canonical.size} icons; ${local.size} animated).`);
